#!/usr/bin/env bash
# Builds the fused direct resolve shaders into a C header.
# Usage: build.sh [output header]
set -euo pipefail

D="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
O="${1:-$D/direct_resolve_shaders.h}"

SDK="${SDK:-$(cd "$D/../../.." && pwd)/../rexglue-sdk-android}"

# Locate glslc from the Android NDK configured by GitHub Actions,
# Android SDK environment variables, or PATH.
G=""

for candidate in \
  "${ANDROID_NDK_HOME:-}/shader-tools/linux-x86_64/glslc" \
  "${ANDROID_NDK_HOME:-}/toolchains/llvm/prebuilt/linux-x86_64/bin/glslc" \
  "${ANDROID_NDK_ROOT:-}/shader-tools/linux-x86_64/glslc" \
  "${ANDROID_NDK_ROOT:-}/toolchains/llvm/prebuilt/linux-x86_64/bin/glslc" \
  "${ANDROID_HOME:-}/ndk/28.2.13676358/shader-tools/linux-x86_64/glslc" \
  "${ANDROID_HOME:-}/ndk/28.2.13676358/toolchains/llvm/prebuilt/linux-x86_64/bin/glslc" \
  "${ANDROID_SDK_ROOT:-}/ndk/28.2.13676358/shader-tools/linux-x86_64/glslc" \
  "${ANDROID_SDK_ROOT:-}/ndk/28.2.13676358/toolchains/llvm/prebuilt/linux-x86_64/bin/glslc" \
  "$HOME/android-sdk/ndk/28.2.13676358/shader-tools/linux-x86_64/glslc"
do
  if [[ -n "$candidate" && -x "$candidate" ]]; then
    G="$candidate"
    break
  fi
done

if [[ -z "$G" ]] && command -v glslc >/dev/null 2>&1; then
  G="$(command -v glslc)"
fi

if [[ -z "$G" ]]; then
  echo "::error::glslc was not found. Check the installed Android NDK and shader-tools package."
  echo "ANDROID_HOME=${ANDROID_HOME:-<unset>}"
  echo "ANDROID_SDK_ROOT=${ANDROID_SDK_ROOT:-<unset>}"
  echo "ANDROID_NDK_HOME=${ANDROID_NDK_HOME:-<unset>}"
  echo "ANDROID_NDK_ROOT=${ANDROID_NDK_ROOT:-<unset>}"
  exit 127
fi

echo "Using glslc: $G"

python3 "$D/make_fused_full.py" \
  "$SDK/src/graphics/shaders/vulkan_spirv/resolve_full_32bpp_cs.h" \
  "$D/direct_resolve_full_32bpp.comp"

T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT

echo "// Generated by tools/android/resolve_shaders/build.sh." > "$O"

for kind in fast full 8888; do
  for m in 0 1; do
    "$G" -O --target-env=vulkan1.0 -fshader-stage=compute -DMSAA="$m" \
      "$D/direct_resolve_${kind}$( [[ "$kind" == 8888 ]] || echo _32bpp).comp" \
      -o "$T/dr.spv"

    echo "const uint32_t direct_resolve_${kind}$( [[ "$kind" == 8888 ]] || echo _32bpp)_msaa${m}_cs[] = {" >> "$O"
    python3 "$D/spv_to_c.py" "$T/dr.spv" >> "$O"
    echo "};" >> "$O"
  done
done

for m in 0 1; do
  "$G" -O --target-env=vulkan1.0 -fshader-stage=compute \
    -DMSAA="$m" -DDEPTH=1 \
    "$D/direct_resolve_fast_32bpp.comp" -o "$T/dr.spv"

  echo "const uint32_t direct_resolve_fast_depth_msaa${m}_cs[] = {" >> "$O"
  python3 "$D/spv_to_c.py" "$T/dr.spv" >> "$O"
  echo "};" >> "$O"
done

wc -c "$O"
